    static_assert(std::size(VKeyNames) == static_cast<size_t>(VKey::VKEYS_COUNT));

    constexpr std::string_view toString(VKey key) noexcept
    {
        const auto index = static_cast<size_t>(key);
        if (index >= static_cast<size_t>(VKey::VKEYS_COUNT))
            return "UNKNOWN";
        return VKeyNames[index];
    }

    constexpr VKey toVKey(std::string_view name) noexcept
    {
        for (size_t i = 0; i < static_cast<size_t>(VKey::VKEYS_COUNT); ++i)
        {
            if (VKeyNames[i] == name)
                return static_cast<VKey>(i);
        }
        return VKey::NONE;
    }
