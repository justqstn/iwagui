namespace std
{
    template <>
    struct formatter<Iwa::VKey>
    {
        constexpr auto parse(format_parse_context& ctx) { return ctx.begin(); }

        template <typename FormatContext>
        auto format(Iwa::VKey key, FormatContext& ctx) const
        {
            return format_to(ctx.out(), "{}", Iwa::toString(key));
        }
    };
} // namespace std
